export default function SettingsLayout({ children }: { children: React.ReactNode }) {
  const { hasRole, currentOrg } = useAuth()
  const location = useLocation()
  const currentPath = location.pathname.replace(/\/+$/, '')

  const isActive = (item: SettingsNavItem) => {
    const itemPath = item.to.replace(/\/+$/, '')
    if (item.exact) return currentPath === itemPath
    return currentPath.startsWith(itemPath)
  }

  return (
    <div className="max-w-[1600px] mx-auto px-4 sm:px-6 lg:px-8 py-6">
      <div className="flex flex-col lg:flex-row gap-6">
        {/* Sidebar */}
        <aside className="lg:w-56 shrink-0">
          <div className="lg:sticky lg:top-20">
            <h2 className="text-xs font-semibold uppercase tracking-wider text-[var(--color-text-muted)] mb-3 px-3">
              Settings
            </h2>
            <nav className="space-y-1">
              {SETTINGS_NAV.filter((item) => hasRole(item.minRole)).map((item) => (
                <Link
                  key={item.to}
                  to={item.to}
                  className={`flex items-center gap-3 px-3 py-2 rounded-lg text-sm font-medium transition-colors ${
                    isActive(item)
                      ? 'bg-[var(--color-accent-muted)] text-[var(--color-accent)]'
                      : 'text-[var(--color-text-secondary)] hover:text-white hover:bg-[var(--color-surface-hover)]'
                  }`}
                >
                  {item.icon}
                  {item.label}
                </Link>
              ))}
            </nav>

            {/* Org info */}
            {currentOrg && (
              <div className="mt-6 px-3 py-3 rounded-lg bg-[var(--color-surface)] border border-[var(--glass-border)]">
                <p className="text-xs font-medium text-white truncate">{currentOrg.business_name || currentOrg.name}</p>
                <p className="text-xs text-[var(--color-text-muted)] mt-0.5 capitalize">{currentOrg.plan ?? 'free'} plan</p>
              </div>
            )}
          </div>
        </aside>

        {/* Content */}
        <main className="flex-1 min-w-0">
          {children}
        </main>
      </div>
    </div>
  )
}
